/** Every clip the badminton scene plays: the moves made here from key poses, and the free ones under our names. */
export function buildBadmintonClips(
  rest: { bones: Record<BoneKey, Quaternion>; hips: HipsRest },
  moves: readonly AnimationClip[],
): AnimationClip[] {
  const made = (Object.keys(MOVE_KEYS) as MadeClip[]).map((name) =>
    poseClip(name, MOVE_KEYS[name], rest.bones, BONES, rest.hips, { smooth: true }),
  );
  const library = (Object.keys(LIBRARY_CLIPS) as (keyof typeof LIBRARY_CLIPS)[]).map((ours) => {
    const theirs = moves.find((c) => c.name === LIBRARY_CLIPS[ours]);
    if (!theirs) throw new Error(`moves.glb has no ${LIBRARY_CLIPS[ours]}`);
    const clip = theirs.clone();
    clip.name = ours;
    return clip;
  });
  return [...made, ...library];
}
